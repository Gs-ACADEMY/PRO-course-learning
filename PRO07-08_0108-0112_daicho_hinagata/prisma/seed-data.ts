/** 3 つの表に入れる行を、番号つきで作る（何度呼んでも同じ中身） */
export function buildRows() {
  const inquiries = projects.map(([, , , , name, body, updatedAt], i) => ({
    id: i + 1,
    name,
    body,
    // 問い合わせを受けた日は、案件の更新日の 20 日以上前
    createdAt: new Date(new Date(updatedAt).getTime() - (20 + i) * 86400000),
  }));

  const projectRows = projects.map(([title, status, amount, assignee, , , updatedAt], i) => ({
    id: i + 1,
    title,
    status,
    amount,
    assignee,
    inquiryId: i + 1, // 案件 1 件に、問い合わせ 1 件
    updatedAt: new Date(updatedAt),
  }));

  // 日報の番号は、案件番号の小さい順に 1 から（Object.entries は数字のキーを小さい順に返す）
  const reports: { id: number; date: Date; workers: number; note: string; projectId: number }[] = [];
  let k = 0;
  for (const [pid, notes] of Object.entries(work)) {
    const days = workdays(starts[Number(pid)], notes.length);
    for (const [j, note] of notes.entries()) {
      reports.push({
        id: reports.length + 1,
        date: new Date(days[j]),
        workers: crew[k++ % crew.length],
        note,
        projectId: Number(pid),
      });
    }
  }

  return { inquiries, projects: projectRows, reports };
}
