// 始める日から、日曜を飛ばして n 日分の日付（日本時間の 0 時）
function workdays(startIso: string, n: number): string[] {
  const out: string[] = [];
  const d = new Date(`${startIso}T00:00:00+09:00`);
  while (out.length < n) {
    const day = new Date(d.getTime() + 9 * 3600 * 1000).getUTCDay();
    if (day !== 0) out.push(new Date(d).toISOString());
    d.setUTCDate(d.getUTCDate() + 1);
  }
  return out;
}
